-- ---------------------------------------------------------------------
-- 1. CATÁLOGO (lo que el administrador edita; los agricultores reciben
--    solo la versión PUBLICADA, nunca el borrador)
-- ---------------------------------------------------------------------
create table if not exists cultivos (
  id text primary key,
  nombre text not null,
  activo boolean not null default true,
  orden int not null default 0
);

create table if not exists etapas (
  id bigint generated by default as identity primary key,
  cultivo_id text not null references cultivos(id) on delete cascade,
  nombre text not null,
  uso text not null default 'ambos' check (uso in ('ambos','sanitario','fertilizacion')),  -- plan sanitario, plan de fertilización o ambos
  semanas text,
  riesgo_hongos text check (riesgo_hongos in ('bajo','ligero','alto')),
  notas text,
  costo_ref_texto text,
  orden int not null default 0
);

create table if not exists productos (
  id bigint generated by default as identity primary key,
  nombre text not null,
  ingrediente_activo text,
  grupo text,
  categoria text not null,
  formulacion text,          -- corrector_ph, polvo, suspension, liquido, emulsion, soluble, liquido_foliar, aceite_adherente, siliconado, granulado, cebo
  modo_aplicacion text not null default 'tanque' check (modo_aplicacion in ('tanque','sitio','suelo_ha')),
  dosis_min numeric,         -- por tanque de 200 L (o por sitio / kg por ha según modo)
  dosis_max numeric,
  unidad text,               -- cc, g, kg/ha
  dosis_texto text,
  presentacion text,
  contenido numeric,         -- contenido del envase en cc o g
  contenido_unidad text,
  pvp numeric,
  control text,
  carencia_dias int,
  reingreso_horas int,
  categoria_tox text,
  nota text,
  fuente text,               -- de dónde salió el dato (Excel del asesor, ficha técnica, internet)
  presentaciones jsonb not null default '[]',  -- [{codigo, empaque, cantidad (cc o g), unidad, precio}] de la lista de precios oficial
  activo boolean not null default true
);

create table if not exists problemas (
  id bigint generated by default as identity primary key,
  cultivo_id text not null references cultivos(id) on delete cascade,
  tipo text not null check (tipo in ('plaga','enfermedad','maleza','nutricion')),
  nombre text not null,
  descripcion text,
  orden int not null default 0,
  fuente text,
  fotos jsonb not null default '[]'   -- [{url, credito}] fotografías referenciales del manual
);
alter table problemas add column if not exists fotos jsonb not null default '[]';

create table if not exists recomendaciones (
  id bigint generated by default as identity primary key,
  problema_id bigint not null references problemas(id) on delete cascade,
  producto_id bigint not null references productos(id) on delete cascade,
  etapa_id bigint references etapas(id) on delete set null,   -- vacío = todas las etapas
  prioridad int not null default 1,
  dosis_min numeric,          -- vacío = usar la dosis del producto
  dosis_max numeric,
  nota text
);

create table if not exists plan_sanitario (
  id bigint generated by default as identity primary key,
  etapa_id bigint not null references etapas(id) on delete cascade,
  producto_id bigint not null references productos(id) on delete cascade,
  dosis_tanque numeric,
  unidad text,
  alternar boolean not null default false,
  orden int not null default 0
);

create table if not exists plan_fertilizacion (
  id bigint generated by default as identity primary key,
  cultivo_id text not null references cultivos(id) on delete cascade,
  etapa_id bigint references etapas(id) on delete cascade,
  tipo text not null check (tipo in ('suelo','foliar','enmienda')),
  producto_id bigint not null references productos(id) on delete cascade,
  dosis_kg_ha numeric,
  dosis_g_planta numeric,
  dosis_tanque numeric,
  frecuencia_dias int,
  condicion text,
  nota text,
  orden int not null default 0
);

create table if not exists compatibilidad (
  id bigint generated by default as identity primary key,
  producto_a bigint not null references productos(id) on delete cascade,
  producto_b bigint not null references productos(id) on delete cascade,
  nivel text not null check (nivel in ('compatible','precaucion','incompatible')),
  nota text
);

create table if not exists ajustes (
  clave text primary key,
  valor jsonb
);

create table if not exists catalogo_publicado (
  version int primary key,
  publicado timestamptz not null default now(),
  publicado_por uuid,
  datos jsonb not null
);


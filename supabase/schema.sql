-- 5. PUBLICAR CATÁLOGO (botón "Publicar a la app" del panel)
-- ---------------------------------------------------------------------
create or replace function publicar_catalogo() returns int
language plpgsql security definer set search_path = public as $$
declare v int; d jsonb;
begin
  if not (es_admin() or session_user = 'postgres') then
    raise exception 'solo_admin';
  end if;
  select coalesce(max(version), 0) + 1 into v from catalogo_publicado;
  d := jsonb_build_object(
    'version', v,
    'publicado', now(),
    'cultivos',           (select coalesce(jsonb_agg(to_jsonb(x) order by x.orden), '[]') from cultivos x where x.activo),
    'etapas',             (select coalesce(jsonb_agg(to_jsonb(x) order by x.cultivo_id, x.orden), '[]') from etapas x),
    'productos',          (select coalesce(jsonb_agg(to_jsonb(x) order by x.nombre), '[]') from productos x where x.activo),
    'problemas',          (select coalesce(jsonb_agg(to_jsonb(x) order by x.orden), '[]') from problemas x),
    'recomendaciones',    (select coalesce(jsonb_agg(to_jsonb(x) order by x.problema_id, x.prioridad), '[]') from recomendaciones x),
    'plan_sanitario',     (select coalesce(jsonb_agg(to_jsonb(x) order by x.etapa_id, x.orden), '[]') from plan_sanitario x),
    'plan_fertilizacion', (select coalesce(jsonb_agg(to_jsonb(x) order by x.etapa_id, x.orden), '[]') from plan_fertilizacion x),
    'compatibilidad',     (select coalesce(jsonb_agg(to_jsonb(x)), '[]') from compatibilidad x),
    'ajustes',            (select coalesce(jsonb_object_agg(clave, valor), '{}') from ajustes)
  );
  insert into catalogo_publicado(version, publicado_por, datos) values (v, auth.uid(), d);
  return v;
end $$;
revoke all on function publicar_catalogo() from public, anon;
grant execute on function publicar_catalogo() to authenticated;


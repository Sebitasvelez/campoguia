create table if not exists lotes (
  id uuid primary key,
  agricultor_id uuid not null references agricultores(id) on delete cascade,
  nombre text not null,
  cultivo_id text,
  hectareas numeric,
  plantas int,
  etapa_id bigint,
  latitud numeric,
  longitud numeric,
  precision_m numeric,
  ubicacion_fecha timestamptz,

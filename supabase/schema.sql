-- ---------------------------------------------------------------------
-- 4. SEGURIDAD (Row Level Security)
--    · Catálogo: solo admins leen y editan el borrador.
--    · Catálogo publicado: lo lee cualquiera (la app lo descarga).
--    · Agricultores/lotes/registros: los admins leen; la app escribe
--      únicamente a través de las funciones app_* de abajo.
-- ---------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['cultivos','etapas','productos','problemas','recomendaciones',
                           'plan_sanitario','plan_fertilizacion','compatibilidad','ajustes'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists admin_todo on %I', t);
    execute format('create policy admin_todo on %I for all to authenticated using (es_admin()) with check (es_admin())', t);
  end loop;
  foreach t in array array['agricultores','lotes','registros'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists admin_lee on %I', t);
    execute format('create policy admin_lee on %I for select to authenticated using (es_admin())', t);
  end loop;
end $$;

drop policy if exists admin_edita on agricultores;
create policy admin_edita on agricultores for update to authenticated using (es_admin()) with check (es_admin());

alter table sesiones enable row level security;          -- sin políticas: nadie la lee por la API
alter table admins enable row level security;
drop policy if exists admin_se_ve on admins;
create policy admin_se_ve on admins for select to authenticated using (user_id = auth.uid());

alter table catalogo_publicado enable row level security;
drop policy if exists todos_leen on catalogo_publicado;
create policy todos_leen on catalogo_publicado for select to anon, authenticated using (true);


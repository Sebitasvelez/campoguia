-- 6. FUNCIONES DE LA APP (ingreso solo con número de celular)
-- ---------------------------------------------------------------------
create or replace function norm_tel(t text) returns text
language sql immutable as $$
  select case
    when d like '593%' then '0' || substr(d, 4)
    when d like '9%' and length(d) = 9 then '0' || d
    else d end
  from (select regexp_replace(coalesce(t, ''), '\D', '', 'g') as d) s;
$$;

-- Cédula ecuatoriana: provincia 01-24 o 30, tercer dígito menor a 6 y dígito verificador (módulo 10)
create or replace function cedula_valida(c text) returns boolean
language plpgsql immutable as $$
declare d text := regexp_replace(coalesce(c, ''), '\D', '', 'g'); s int := 0; v int; i int;
begin
  if length(d) <> 10 then return false; end if;
  if not ((substr(d,1,2)::int between 1 and 24) or substr(d,1,2)::int = 30) then return false; end if;
  if substr(d,3,1)::int >= 6 then return false; end if;
  for i in 1..9 loop
    v := substr(d,i,1)::int * (case when i % 2 = 1 then 2 else 1 end);
    if v > 9 then v := v - 9; end if;
    s := s + v;
  end loop;
  return (10 - s % 10) % 10 = substr(d,10,1)::int;
end $$;

create or replace function _agricultor(p_token uuid) returns agricultores
language plpgsql stable security definer set search_path = public as $$
declare a agricultores;
begin
  select ag.* into a from sesiones s join agricultores ag on ag.id = s.agricultor_id
   where s.token = p_token and ag.activo;
  if a.id is null then raise exception 'sesion_invalida'; end if;
  return a;
end $$;
revoke all on function _agricultor(uuid) from public, anon, authenticated;

create or replace function _perfil(a agricultores) returns jsonb
language sql immutable as $$
  select jsonb_build_object('id', a.id, 'cedula', a.cedula, 'nombres', a.nombres, 'telefono', a.telefono,
    'cultivo_id', a.cultivo_id, 'hectareas', a.hectareas, 'provincia', a.provincia, 'sector', a.sector,
    'comunidad', a.comunidad, 'rol', a.rol, 'latitud', a.latitud, 'longitud', a.longitud, 'precision_m', a.precision_m,
    'ubicacion_fecha', a.ubicacion_fecha, 'acepta_seguimiento', a.acepta_seguimiento);
$$;

create or replace function app_registrar(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare a agricultores; t uuid; tel text := norm_tel(p->>'telefono'); ced text := regexp_replace(coalesce(p->>'cedula',''), '\D', '', 'g');
begin
  if not cedula_valida(ced) then raise exception 'cedula_invalida'; end if;
  if length(tel) < 9 then raise exception 'telefono_invalido'; end if;
  if coalesce(trim(p->>'nombres'), '') = '' then raise exception 'nombre_requerido'; end if;
  if coalesce(trim(p->>'provincia'), '') = '' or coalesce(trim(p->>'sector'), '') = '' then raise exception 'ubicacion_requerida'; end if;
  if exists (select 1 from agricultores where cedula = ced) then raise exception 'cedula_ya_registrada'; end if;
  insert into agricultores(cedula, nombres, telefono, cultivo_id, hectareas, provincia, sector, comunidad, rol, acepta_seguimiento,
                           latitud, longitud, precision_m, ubicacion_fecha, ultimo_ingreso)
  values (ced, trim(p->>'nombres'), tel, p->>'cultivo_id', nullif(p->>'hectareas','')::numeric,
          trim(p->>'provincia'), trim(p->>'sector'), nullif(trim(p->>'comunidad'),''), coalesce(nullif(p->>'rol',''), 'agricultor'),
          coalesce((p->>'acepta_seguimiento')::boolean, true),
          nullif(p->>'latitud','')::numeric, nullif(p->>'longitud','')::numeric, nullif(p->>'precision_m','')::numeric,
          case when nullif(p->>'latitud','') is not null then now() end, now())
  returning * into a;
  insert into sesiones(agricultor_id) values (a.id) returning token into t;
  return jsonb_build_object('token', t, 'perfil', _perfil(a));
end $$;

create or replace function app_ingresar(p_cedula text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare a agricultores; t uuid;
begin
  select * into a from agricultores where cedula = regexp_replace(coalesce(p_cedula,''), '\D', '', 'g') and activo;
  if a.id is null then raise exception 'no_registrado'; end if;
  update agricultores set ultimo_ingreso = now() where id = a.id;
  insert into sesiones(agricultor_id) values (a.id) returning token into t;
  return jsonb_build_object('token', t, 'perfil', _perfil(a));
end $$;

create or replace function app_mis_datos(p_token uuid) returns jsonb
language plpgsql security definer set search_path = public as $$
declare a agricultores := _agricultor(p_token);
begin
  return jsonb_build_object(
    'perfil', _perfil(a),
    'lotes', (select coalesce(jsonb_agg(to_jsonb(l) order by l.nombre), '[]') from lotes l where l.agricultor_id = a.id and not l.borrado),
    'registros', (select coalesce(jsonb_agg(to_jsonb(r) order by r.fecha desc), '[]') from registros r where r.agricultor_id = a.id and not r.borrado));
end $$;

-- Recibe los cambios hechos sin internet y devuelve todo actualizado
create or replace function app_sincronizar(p_token uuid, p_lotes jsonb, p_registros jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare a agricultores := _agricultor(p_token); x jsonb;
begin
  for x in select * from jsonb_array_elements(coalesce(p_lotes, '[]')) loop
    insert into lotes(id, agricultor_id, nombre, cultivo_id, hectareas, plantas, etapa_id, latitud, longitud, precision_m, ubicacion_fecha, borrado, actualizado)
    values ((x->>'id')::uuid, a.id, x->>'nombre', x->>'cultivo_id', nullif(x->>'hectareas','')::numeric,
            nullif(x->>'plantas','')::int, nullif(x->>'etapa_id','')::bigint,
            nullif(x->>'latitud','')::numeric, nullif(x->>'longitud','')::numeric, nullif(x->>'precision_m','')::numeric,
            nullif(x->>'ubicacion_fecha','')::timestamptz, coalesce((x->>'borrado')::boolean, false), now())
    on conflict (id) do update set nombre = excluded.nombre, cultivo_id = excluded.cultivo_id, hectareas = excluded.hectareas,
      plantas = excluded.plantas, etapa_id = excluded.etapa_id, latitud = excluded.latitud, longitud = excluded.longitud,
      precision_m = excluded.precision_m, ubicacion_fecha = excluded.ubicacion_fecha, borrado = excluded.borrado, actualizado = now()
    where lotes.agricultor_id = a.id;
  end loop;
  for x in select * from jsonb_array_elements(coalesce(p_registros, '[]')) loop
    insert into registros(id, agricultor_id, lote_id, fecha, actividad, producto_id, producto_nombre, dosis, unidad, aplicador,
                          clima, costo, observaciones, proxima_fecha, carencia_hasta, borrado, actualizado)
    values ((x->>'id')::uuid, a.id, nullif(x->>'lote_id','')::uuid, (x->>'fecha')::date, x->>'actividad',
            nullif(x->>'producto_id','')::bigint, x->>'producto_nombre', nullif(x->>'dosis','')::numeric, x->>'unidad',
            x->>'aplicador', x->>'clima', nullif(x->>'costo','')::numeric, x->>'observaciones',
            nullif(x->>'proxima_fecha','')::date, nullif(x->>'carencia_hasta','')::date,
            coalesce((x->>'borrado')::boolean, false), now())
    on conflict (id) do update set lote_id = excluded.lote_id, fecha = excluded.fecha, actividad = excluded.actividad,
      producto_id = excluded.producto_id, producto_nombre = excluded.producto_nombre, dosis = excluded.dosis,
      unidad = excluded.unidad, aplicador = excluded.aplicador, clima = excluded.clima, costo = excluded.costo,
      observaciones = excluded.observaciones, proxima_fecha = excluded.proxima_fecha,
      carencia_hasta = excluded.carencia_hasta, borrado = excluded.borrado, actualizado = now()
    where registros.agricultor_id = a.id;
  end loop;
  return app_mis_datos(p_token);
end $$;

create or replace function app_actualizar_perfil(p_token uuid, p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare a agricultores := _agricultor(p_token);
begin
  update agricultores set nombres = coalesce(nullif(trim(p->>'nombres'),''), nombres),
    cultivo_id = coalesce(p->>'cultivo_id', cultivo_id),
    hectareas = coalesce(nullif(p->>'hectareas','')::numeric, hectareas),
    comunidad = coalesce(p->>'comunidad', comunidad),
    telefono = coalesce(nullif(norm_tel(p->>'telefono'), ''), telefono),
    provincia = coalesce(nullif(p->>'provincia',''), provincia),
    sector = coalesce(nullif(p->>'sector',''), sector),
    latitud = coalesce(nullif(p->>'latitud','')::numeric, latitud),
    longitud = coalesce(nullif(p->>'longitud','')::numeric, longitud),
    precision_m = coalesce(nullif(p->>'precision_m','')::numeric, precision_m),
    ubicacion_fecha = case when nullif(p->>'latitud','') is not null then now() else ubicacion_fecha end,
    acepta_seguimiento = coalesce((p->>'acepta_seguimiento')::boolean, acepta_seguimiento)
  where id = a.id returning * into a;
  return _perfil(a);
end $$;

create or replace function app_cerrar_sesion(p_token uuid) returns void
language sql security definer set search_path = public as $$
  delete from sesiones where token = p_token;
$$;

grant execute on function app_registrar(jsonb), app_ingresar(text), cedula_valida(text), app_mis_datos(uuid),
  app_sincronizar(uuid, jsonb, jsonb), app_actualizar_perfil(uuid, jsonb), app_cerrar_sesion(uuid) to anon, authenticated;

-- ============================================================
-- Fotografías del manual: carpeta pública «fotos» en Supabase Storage.
-- Todos pueden verlas; solo los administradores suben, cambian o borran.
-- ============================================================
do $$
begin
  if to_regclass('storage.buckets') is not null then
    insert into storage.buckets (id, name, public) values ('fotos', 'fotos', true) on conflict (id) do update set public = true;
    drop policy if exists "fotos_leer" on storage.objects;
    drop policy if exists "fotos_admin_subir" on storage.objects;
    drop policy if exists "fotos_admin_cambiar" on storage.objects;
    drop policy if exists "fotos_admin_borrar" on storage.objects;
    create policy "fotos_leer" on storage.objects for select using (bucket_id = 'fotos');
    create policy "fotos_admin_subir" on storage.objects for insert to authenticated with check (bucket_id = 'fotos' and public.es_admin());
    create policy "fotos_admin_cambiar" on storage.objects for update to authenticated using (bucket_id = 'fotos' and public.es_admin());
    create policy "fotos_admin_borrar" on storage.objects for delete to authenticated using (bucket_id = 'fotos' and public.es_admin());
  end if;
end $$;

